import * as T from "three";
import { mergeGeometries } from "three/addons/utils/BufferGeometryUtils.js";

const TAU = Math.PI * 2;
const V = (p) => new T.Vector3(...p);
const MEMBRANE = "erythrocyteMembrane";
const CYTOSOL = "erythrocyteCytosol";
const resources = new WeakMap();
function add(g, geometry, color, id, flags = {}) {
  if (!resources.has(g)) resources.set(g, new Map());
  const materials = resources.get(g);
  if (!materials.has(color))
    materials.set(
      color,
      new T.MeshPhysicalMaterial({
        color,
        roughness: 0.49,
        clearcoat: 0.14,
        side: T.DoubleSide,
      }),
    );
  const m = new T.Mesh(geometry, materials.get(color));
  m.userData = { hitId: id, ...flags };
  g.add(m);
  return m;
}
function batch(g, parts, color, id, flags = {}) {
  const geometry = mergeGeometries(parts);
  parts.forEach((p) => p.dispose());
  return add(g, geometry, color, id, flags);
}
function sphere(p, scale) {
  return new T.SphereGeometry(1, 16, 12).scale(...scale).translate(...p);
}
function tube(points, radius = 0.025, steps = 28) {
  return new T.TubeGeometry(
    new T.CatmullRomCurve3(points.map(V)),
    steps,
    radius,
    8,
    false,
  );
}
function rod(a, b, r = 0.02) {
  const av = V(a),
    bv = V(b),
    d = bv.clone().sub(av);
  const geo = new T.CylinderGeometry(r, r, d.length(), 8);
  geo.applyQuaternion(
    new T.Quaternion().setFromUnitVectors(
      new T.Vector3(0, 1, 0),
      d.normalize(),
    ),
  );
  geo.translate(...av.lerp(bv, 0.5).toArray());
  return geo;
}

// Evans–Fung axisymmetric profile in μm. Both poles have a nonzero z;
// lathe meridians meet on the axis, so the depression is never a hole.
export function erythrocyteHalfThickness(radiusFraction) {
  const r2 = T.MathUtils.clamp(radiusFraction, 0, 1) ** 2;
  return 0.5 * Math.sqrt(1 - r2) * (0.81 + 7.83 * r2 - 4.39 * r2 * r2);
}
function profile(scale) {
  return Array.from({ length: 161 }, (_, i) => {
    const t = (Math.PI * i) / 160,
      r = Math.sin(t);
    return new T.Vector2(
      3.91 * r * scale,
      Math.sign(t - Math.PI / 2) * erythrocyteHalfThickness(r) * scale,
    );
  });
}
function surface(scale, start, length) {
  return new T.LatheGeometry(profile(scale), 112, start, length).rotateX(
    Math.PI / 2,
  );
}
function section(scale, phi) {
  const geo = new T.ShapeGeometry(new T.Shape(profile(scale)));
  const p = geo.attributes.position;
  for (let i = 0; i < p.count; i++) {
    const r = p.getX(i),
      z = p.getY(i);
    p.setXYZ(i, r * Math.sin(phi), -r * Math.cos(phi), z);
  }
  geo.computeVertexNormals();
  return geo;
}
function rim(scale, phi) {
  return tube(
    profile(scale).map((p) => [p.x * Math.sin(phi), -p.x * Math.cos(phi), p.y]),
    0.012,
    180,
  );
}
function whole() {
  const g = new T.Group(),
    s = 1.9 / 3.91,
    angle = 1.5 * Math.PI;
  for (const cap of [false, true]) {
    const start = cap ? angle : 0,
      length = cap ? TAU - angle : angle;
    add(g, surface(s, start, length), "#c65363", MEMBRANE, { cap });
    add(g, surface(s * 0.985, start, length), "#a83e51", CYTOSOL, { cap });
  }
  for (const phi of [0, angle]) {
    add(g, section(s * 0.985, phi), "#cf7b83", CYTOSOL, { cutOnly: true });
    add(g, rim(s, phi), "#e9b3ac", MEMBRANE, { cutOnly: true });
  }
  g.rotation.set(-0.28, -0.34, -0.2);
  g.userData.partAnchors = {
    // Retained front-surface vertex: the lower-left wedge disappears on section.
    [MEMBRANE]: [-1.169797, 0.712347, 0.621947],
    [CYTOSOL]: [-0.68, 0, 0.2],
  };
  g.userData.partLabelModes = { [CYTOSOL]: ["section", "explode"] };
  g.userData.landmarks = [
    {
      zh: "中央变薄，非孔洞",
      en: "Thin centre, no hole",
      position: [0, 0, 0.197],
    },
  ];
  return g;
}

// Enlarged patch; spacing, protein shapes and bilayer/skeleton separation are
// educational, not an atomic reconstruction or a claim of crystalline order.
function membrane() {
  const g = new T.Group(),
    heads = [[], []],
    tails = [],
    spectrin = [],
    actin = [],
    protein = [],
    anchors = [];
  const band = [-0.48, 0.12];
  for (let row = -5; row <= 5; row++)
    for (let col = -10; col <= 10; col++) {
      const x = col * 0.18 + (row % 2) * 0.09,
        z = row * 0.19;
      if ((x - band[0]) ** 2 + (z - band[1]) ** 2 < 0.27 ** 2) continue;
      for (const [i, sign] of [-1, 1].entries()) {
        heads[i].push(sphere([x, sign * 0.255, z], [0.073, 0.06, 0.073]));
        for (const side of [-1, 1])
          tails.push(
            tube(
              [
                [x + side * 0.025, sign * 0.208, z],
                [x + side * 0.025, sign * 0.13, z + 0.014],
                [x + side * 0.025 + (side > 0 ? 0.035 : 0), sign * 0.025, z],
              ],
              0.014,
              5,
            ),
          );
      }
    }
  batch(g, heads[1], "#dcbba9", MEMBRANE);
  batch(g, heads[0], "#b99089", MEMBRANE);
  batch(g, tails, "#c4a17b", MEMBRANE);
  // Sparse triangulated spectrin connections converge on short actin nodes;
  // not six obligatory neighbours or a universal geometrically regular mesh.
  const nodes = [
    [-1.6, -0.83, -0.8],
    [-0.5, -0.84, -0.8],
    [0.65, -0.82, -0.77],
    [1.55, -0.8, -0.58],
    [-1.1, -0.83, 0.16],
    [0.07, -0.85, 0.2],
    [1.22, -0.81, 0.35],
    [-1.65, -0.83, 0.87],
    [-0.52, -0.82, 0.86],
    [0.62, -0.84, 0.86],
  ];
  const edges = [
    [0, 1],
    [1, 2],
    [2, 3],
    [0, 4],
    [1, 4],
    [1, 5],
    [2, 5],
    [2, 6],
    [3, 6],
    [4, 5],
    [5, 6],
    [4, 7],
    [4, 8],
    [5, 8],
    [5, 9],
    [6, 9],
    [7, 8],
    [8, 9],
  ];
  for (const [a, b] of edges) {
    const p = V(nodes[a]),
      q = V(nodes[b]),
      mid = p.clone().lerp(q, 0.5);
    // Twin strands schematize alpha/beta spectrin pairing, not molecular helices.
    for (const offset of [-0.018, 0.018])
      spectrin.push(
        tube(
          [
            p.toArray(),
            p
              .clone()
              .lerp(q, 0.25)
              .add(new T.Vector3(0, -0.04, offset))
              .toArray(),
            mid
              .clone()
              .add(new T.Vector3(0, -0.07, offset))
              .toArray(),
            p
              .clone()
              .lerp(q, 0.75)
              .add(new T.Vector3(0, -0.03, offset))
              .toArray(),
            q.toArray(),
          ],
          0.018,
          18,
        ),
      );
  }
  for (const p of nodes) {
    for (let i = 0; i < 5; i++)
      actin.push(
        sphere(
          [p[0] + (i - 2) * 0.053, p[1], p[2] + (i % 2 ? 0.022 : -0.022)],
          [0.047, 0.039, 0.039],
        ),
      );
  }
  batch(g, spectrin, "#91afa6", MEMBRANE);
  batch(g, actin, "#c8a565", MEMBRANE);
  for (const dx of [-0.1, 0.1]) {
    protein.push(sphere([band[0] + dx, 0.01, band[1]], [0.13, 0.36, 0.19]));
    protein.push(sphere([band[0] + dx, -0.39, band[1]], [0.17, 0.17, 0.18]));
  }
  batch(g, protein, "#77949f", MEMBRANE);
  anchors.push(
    tube(
      [
        [band[0], -0.48, band[1]],
        [-0.39, -0.61, 0.15],
        [-0.26, -0.81, 0.18],
      ],
      0.062,
      16,
    ),
  );
  batch(g, anchors, "#d2b077", MEMBRANE);
  g.rotation.set(0.28, -0.24, -0.1);
  g.userData.landmarks = [
    {
      zh: "胞外侧 · 脂质头部",
      en: "Extracellular lipid heads",
      position: [1.35, 0.29, -0.55],
    },
    {
      zh: "双层疏水尾部",
      en: "Hydrophobic bilayer core",
      position: [1.8, 0, 0.9],
    },
    {
      zh: "胞质侧血影蛋白网",
      en: "Cytoplasmic spectrin network",
      position: [0.48, -0.88, 0.8],
    },
    {
      zh: "短肌动蛋白连接点",
      en: "Short actin junction",
      position: [-1.1, -0.83, 0.16],
    },
    { zh: "带 3 二聚体", en: "Band 3 dimer", position: [-0.48, 0.35, 0.12] },
    {
      zh: "锚蛋白连接",
      en: "Ankyrin attachment",
      position: [-0.36, -0.65, 0.15],
    },
  ];
  g.userData.molecularDetail = {
    schematic: true,
    bilayerLeaflets: 2,
    cytoplasmicSkeleton: true,
    actinJunctions: nodes.length,
    spectrinConnections: edges.length,
  };
  return g;
}

function haemoglobin() {
  const g = new T.Group(),
    all = Object.values(HB.chains).flat(),
    bounds = new T.Box3();
  all.forEach((row) => bounds.expandByPoint(V(row.slice(1))));
  const center = bounds.getCenter(new T.Vector3()),
    scale = 3.65 / Math.max(...bounds.getSize(new T.Vector3()).toArray());
  const point = (p) => V(p).sub(center).multiplyScalar(scale);
  const chainColors = {
    A: "#bd6d7b",
    B: "#9db8b2",
    C: "#d69b9e",
    D: "#729c98",
  };
  const landmarks = [];
  for (const [chain, rows] of Object.entries(HB.chains)) {
    let segment = [],
      previous = null;
    const segments = [];
    for (const row of rows) {
      const p = point(row.slice(1));
      if (
        previous &&
        (row[0] !== previous[0] + 1 ||
          V(row.slice(1)).distanceTo(V(previous.slice(1))) > 6)
      ) {
        segments.push(segment);
        segment = [];
      }
      segment.push(p.toArray());
      previous = row;
    }
    segments.push(segment);
    batch(
      g,
      segments
        .filter((p) => p.length > 1)
        .map((p) => tube(p, 0.047, 4 * (p.length - 1))),
      chainColors[chain],
      CYTOSOL,
    );
    const c = rows
      .reduce((v, row) => v.add(point(row.slice(1))), new T.Vector3())
      .divideScalar(rows.length);
    landmarks.push({
      zh: `${"AC".includes(chain) ? "α" : "β"} 亚基 ${chain} · 实验主链`,
      en: `${"AC".includes(chain) ? "α" : "β"} subunit ${chain} · Cα trace`,
      position: c.toArray(),
    });
  }
  const bonds = [],
    atoms = [],
    irons = [];
  for (const heme of Object.values(HB.hemes)) {
    for (let i = 0; i < heme.length; i++) {
      const [name, ...raw] = heme[i],
        p = point(raw);
      if (name === "FE") {
        irons.push(sphere(p.toArray(), [0.065, 0.065, 0.065]));
        continue;
      }
      atoms.push(sphere(p.toArray(), [0.026, 0.026, 0.026]));
      for (let j = i + 1; j < heme.length; j++) {
        if (heme[j][0] === "FE") continue;
        const distance = V(raw).distanceTo(V(heme[j].slice(1)));
        if (distance > 1 && distance < 1.85)
          bonds.push(
            rod(p.toArray(), point(heme[j].slice(1)).toArray(), 0.018),
          );
      }
    }
  }
  batch(g, bonds, "#cba260", CYTOSOL);
  batch(g, atoms, "#e2bb79", CYTOSOL);
  batch(g, irons, "#b7744b", CYTOSOL);
  landmarks.push({
    zh: "四个血红素 · 去氧态，无结合 O₂",
    en: "Four hemes · deoxy state, no bound O₂",
    position: point(HB.hemes.A.find((a) => a[0] === "FE").slice(1)).toArray(),
  });
  g.userData.landmarks = landmarks;
  g.userData.molecularDetail = {
    pdb: "2HHB",
    experimental: true,
    alphaChains: 2,
    betaChains: 2,
    hemes: 4,
    caResidues: 574,
    coordinateRepresentation:
      "C-alpha trace plus heme heavy-atom bonds; side chains omitted",
    soluble: true,
  };
  return g;
}

export function buildErythrocyte(id = "erythrocyte") {
  const g =
    id === MEMBRANE ? membrane() : id === CYTOSOL ? haemoglobin() : whole();
  g.userData.ownedGeometry = true;
  g.userData.specimenId = "erythrocyte";
  g.userData.biology = {
    species: "Homo sapiens",
    mature: true,
    nuclei: 0,
    mitochondria: 0,
    diameterMicrometres: 7.82,
    centralThicknessMicrometres: 0.81,
  };
  g.userData.partAnchors ??= {};
  return g;
}

